# gerar-textos.ps1 — v1.9.0 (acesso amplo: inglês)
# Gera src\VelocimetroInternet\Recursos\Textos.Designer.cs a partir de Textos.resx.
#
# Por quê existe: o `dotnet build` do SDK embute o .resx no assembly, mas NÃO gera a classe
# fortemente tipada (isso é tarefa do Visual Studio/ResXFileCodeGenerator, que esta máquina não
# tem). Sem a classe, o XAML não teria {x:Static r:Textos.Chave} nem o C# `Textos.Chave`.
#
# Uso (na raiz do projeto), SEMPRE que editar o Textos.resx:
#   pwsh -File tools\gerar-textos.ps1
#
# O Textos.Designer.cs é COMMITADO (o build não roda este script): quem clonar compila direto.
# A parte "à mão" da classe (ResourceManager, Culture, Formatar) fica em Recursos\Textos.cs.
$ErrorActionPreference = 'Stop'

$raiz = Split-Path $PSScriptRoot -Parent
$pasta = Join-Path $raiz 'src\VelocimetroInternet\Recursos'
$resx = Join-Path $pasta 'Textos.resx'
$saida = Join-Path $pasta 'Textos.Designer.cs'

[xml]$xml = Get-Content $resx -Encoding utf8
$dados = @($xml.root.data | Sort-Object { $_.name })
if ($dados.Count -eq 0) { throw "Nenhum <data> em $resx" }

$sb = [Text.StringBuilder]::new()
[void]$sb.AppendLine('// <auto-generated>')
[void]$sb.AppendLine('//     Gerado por tools\gerar-textos.ps1 a partir de Recursos\Textos.resx — NÃO EDITE À MÃO.')
[void]$sb.AppendLine('//     Edite o Textos.resx (e o Textos.en.resx) e rode o script de novo.')
[void]$sb.AppendLine('// </auto-generated>')
[void]$sb.AppendLine('#nullable enable')
[void]$sb.AppendLine('namespace VelocimetroInternet.Recursos;')
[void]$sb.AppendLine()
[void]$sb.AppendLine('/// <summary>Textos da interface, fortemente tipados (v1.9.0). A cultura vem de <see cref="Textos.Culture"/> ou de <see cref="Sistema.Idioma.Cultura"/>.</summary>')
[void]$sb.AppendLine('public static partial class Textos')
[void]$sb.AppendLine('{')
foreach ($d in $dados) {
    $nome = [string]$d.name
    if ($nome -notmatch '^[A-Za-z_][A-Za-z0-9_]*$') { throw "Chave inválida para C#: $nome" }
    # O resumo mostra o texto pt-BR (1ª linha, até 100 caracteres) para quem lê o código
    $texto = ([string]$d.value) -replace '\s+', ' '
    if ($texto.Length -gt 100) { $texto = $texto.Substring(0, 100) + '…' }
    $texto = [Security.SecurityElement]::Escape($texto)
    [void]$sb.AppendLine("    /// <summary>$texto</summary>")
    [void]$sb.AppendLine("    public static string $nome => Obter(`"$nome`");")
    [void]$sb.AppendLine()
}
[void]$sb.AppendLine('}')
[IO.File]::WriteAllText($saida, $sb.ToString().TrimEnd() + "`r`n", [Text.UTF8Encoding]::new($true))
"Textos.Designer.cs gerado com $($dados.Count) chaves."
